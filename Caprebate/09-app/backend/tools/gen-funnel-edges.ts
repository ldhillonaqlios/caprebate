/**
 * PHASE 157 (the sweep): WRITES src/web/funnel-edges.ts FROM THE DATABASE'S OWN SCHEMA.
 *
 *   node tools/gen-funnel-edges.ts          rewrite the file
 *   (test/phase157.test.ts compares the file with funnelEdges() on every run)
 *
 * Every foreign key whose PARENT is one of the funnel's own tables (src/web/funnel-deletable.ts) becomes an edge with
 * two literal, parameterised statements: one reading the parent's key columns by rowid, one finding the child rows
 * that point at them. So the deletion plan walks the real schema without building SQL from strings at run time.
 */
import { writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Db, migrate } from '../src/db.ts';
import { MIGRATIONS_DIR } from '../src/app.ts';
import { FUNNEL_DELETABLE_TABLES, type FunnelEdge } from '../src/web/funnel-deletable.ts';

export function funnelEdges(db: Db): FunnelEdge[] {
  const out: FunnelEdge[] = [];
  const tables = db.all<{ name: string }>("SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name").map((r) => r.name);
  for (const child of tables) {
    const rows = db.all<{ id: number; seq: number; table: string; from: string; to: string | null }>('SELECT id, seq, "table", "from", "to" FROM pragma_foreign_key_list(?)', [child]);
    const byId = new Map<number, typeof rows>();
    for (const r of rows) byId.set(r.id, [...(byId.get(r.id) ?? []), r]);
    for (const parts of [...byId.values()]) {
      const sorted = [...parts].sort((a, b) => a.seq - b.seq);
      const parent = sorted[0]!.table;
      if (!FUNNEL_DELETABLE_TABLES.includes(parent)) continue;
      const pk = db.all<{ name: string; pk: number }>('SELECT name, pk FROM pragma_table_info(?) WHERE pk > 0 ORDER BY pk', [parent]).map((c) => c.name);
      const parent_cols = sorted.map((p, i) => p.to ?? pk[i] ?? 'rowid');
      const child_cols = sorted.map((p) => p.from);
      out.push({
        parent, child, parent_cols, child_cols,
        parent_sql: ['SELECT', parent_cols.map((c) => `"${c}"`).join(', '), 'FROM', `"${parent}"`, 'WHERE rowid = ?'].join(' '),
        child_sql: ['SELECT rowid FROM', `"${child}"`, 'WHERE', child_cols.map((c) => `"${c}" = ?`).join(' AND ')].join(' '),
      });
    }
  }
  return out.sort((a, b) => (a.parent + a.child + a.child_cols.join()).localeCompare(b.parent + b.child + b.child_cols.join()));
}

export function render(edges: readonly FunnelEdge[]): string {
  const del = FUNNEL_DELETABLE_TABLES.map((t) => `  ${JSON.stringify(t)}: ${JSON.stringify(['DELETE FROM', `"${t}"`, 'WHERE rowid = ?'].join(' '))},`);
  return [
    '/**',
    ' * GENERATED by tools/gen-funnel-edges.ts from the database schema (Phase 157). Do not edit by hand: re-run the tool.',
    ' * Every foreign key whose parent is one of the funnel\'s own tables (src/web/funnel-deletable.ts), as two literal,',
    ' * parameterised statements. test/phase157.test.ts fails when the schema and this file disagree.',
    ' */',
    "import type { FunnelEdge } from './funnel-deletable.ts';",
    '',
    'export const FUNNEL_EDGES: readonly FunnelEdge[] = Object.freeze([',
    ...edges.map((e) => `  ${JSON.stringify(e)},`),
    ']);',
    '',
    '/** One literal statement per funnel table, deleting one row by rowid. */',
    'export const FUNNEL_DELETE_SQL: Readonly<Record<string, string>> = Object.freeze({',
    ...del,
    '});',
    '',
  ].join('\n');
}

if (fileURLToPath(import.meta.url) === resolve(process.argv[1] ?? '')) {
  const db = new Db(':memory:');
  migrate(db, MIGRATIONS_DIR);
  const edges = funnelEdges(db);
  writeFileSync(join(import.meta.dirname, '..', 'src', 'web', 'funnel-edges.ts'), render(edges));
  console.log(`wrote src/web/funnel-edges.ts: ${String(edges.length)} edges`);
}
