#!/usr/bin/env node
/**
 * PHASE 133c — THE HELP PAGES ARE THE USER GUIDE'S PART 3, COPIED IN, NEVER RETYPED.
 *
 * Reads 09-app/CAPREBATE-ADMIN-AND-USER-GUIDE.md, cuts Part 3 ("Training, one screen at a time") into its training
 * sections, and writes src/web/help-content.ts: one constant per section with the screen codes it covers and its
 * markdown exactly as the guide has it. The application serves Help from that constant, the way it serves the
 * stylesheet and the logo, so there is still no route that reads a file.
 *
 *   node tools/build-help.cjs           write src/web/help-content.ts
 *   node tools/build-help.cjs --check   exit 1 if it is stale against the guide (test/phase133c.test.ts runs this)
 *
 * Change the guide, then run this. Never edit help-content.ts by hand.
 */
'use strict';
const fs = require('node:fs');
const path = require('node:path');

const GUIDE = path.join(__dirname, '..', '..', 'CAPREBATE-ADMIN-AND-USER-GUIDE.md');
const OUT = path.join(__dirname, '..', 'src', 'web', 'help-content.ts');

function codesOf(heading) {
  const out = [];
  for (const m of heading.matchAll(/`([BC])(\d+)`(?:\s*[–-]\s*`[BC](\d+)`)?/g)) {
    const from = Number(m[2]); const to = m[3] === undefined ? from : Number(m[3]);
    for (let n = from; n <= to; n++) out.push(`${m[1]}${n}`);
  }
  for (const m of heading.matchAll(/`([BC])(\d+)`\/`[BC](\d+)`/g)) out.push(`${m[1]}${m[3]}`);
  return [...new Set(out)];
}

function build() {
  const text = fs.readFileSync(GUIDE, 'utf8').replace(/\r\n/g, '\n');
  const start = text.indexOf('\n## Part 3');
  if (start < 0) throw new Error('the guide has no "## Part 3" heading');
  const rest = text.slice(start + 1);
  const next = rest.slice(3).search(/\n## /);
  const part3 = next < 0 ? rest : rest.slice(0, next + 3);
  const chunks = part3.split(/\n(?=### Training — )/);
  const intro = chunks.shift() ?? '';
  const sections = chunks.map((c) => {
    const nl = c.indexOf('\n');
    const heading = c.slice(0, nl).replace(/^### /, '');
    const body = c.slice(nl + 1).replace(/\n---\s*$/, '').trim();
    return { codes: codesOf(heading), title: heading.replace(/^Training — /, '').replace(/`/g, ''), markdown: body };
  });
  const src = `/**
 * GENERATED BY tools/build-help.cjs FROM 09-app/CAPREBATE-ADMIN-AND-USER-GUIDE.md, PART 3. DO NOT EDIT BY HAND.
 * Change the guide and run \`node tools/build-help.cjs\`; \`--check\` fails when this file is stale.
 */

export type HelpSection = { readonly codes: readonly string[]; readonly title: string; readonly markdown: string };

export const HELP_INTRO: string = ${JSON.stringify(intro.replace(/^## [^\n]*\n/, '').trim())};

export const HELP_SECTIONS: readonly HelpSection[] = ${JSON.stringify(sections, null, 1)};
`;
  return src;
}

const out = build();
if (process.argv.includes('--check')) {
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (have !== out) { console.error('src/web/help-content.ts is stale against the user guide: run node tools/build-help.cjs'); process.exit(1); }
  console.log('help-content.ts matches the user guide');
} else {
  fs.writeFileSync(OUT, out);
  console.log(`wrote ${path.relative(process.cwd(), OUT)}`);
}
